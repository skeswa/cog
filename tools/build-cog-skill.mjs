#!/usr/bin/env node

// Generates the installable agent skill under `skills/cog/` from the docs.
//
//     node tools/build-cog-skill.mjs          # write the skill
//     node tools/build-cog-skill.mjs --check  # fail if the skill is stale
//
// A skill is what `npx skills add skeswa/cog` and Claude Code's
// `/plugin install cog@cog` copy into an agent's configuration: a `SKILL.md`
// the agent reads when the task matches its description, plus reference
// files it opens on demand. The `SKILL.md` here is `docs/swift/agent-guide.md`
// and the references are the handbook chapters. Neither is written by hand.
// The docs are the source of truth and the skill is a rendering of them, the
// same way `mise run docs:mark` renders the site mark, so a convention that
// changes in the handbook cannot quietly stay stale in the skill. The `.md`
// twins the docs site publishes and Context7's index both come straight from
// the docs, so this generator is the only place the docs are transformed.
//
// Three transformations are needed, and they are all mechanical:
//
// - Links between the copied pages become links between the copied files.
//   Links to pages the skill does not carry become absolute URLs to the
//   page's Markdown twin on the site, because a relative link is meaningless
//   once the skill has been copied out of this repository.
// - VitePress-only syntax is flattened: `::: tip` containers become
//   blockquotes and code-fence filename labels are dropped, since neither
//   renders outside VitePress.
// - The "Point your agent here" section is removed from `SKILL.md`. An agent
//   reading the skill has already been pointed here.
//
// The check mode exists for the same reason `check-getting-started.mjs`
// does: the generated files are committed, so the build must prove they match
// their sources rather than trust that somebody re-ran the generator.

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));
const SITE_URL = "https://skeswa.github.io/cog";
const GUIDE_PATH = "docs/swift/agent-guide.md";
const HANDBOOK_DIRECTORY = "docs/swift/handbook";
const SKILL_DIRECTORY = "skills/cog";
const REFERENCES_DIRECTORY = `${SKILL_DIRECTORY}/references`;

/** The `SKILL.md` frontmatter. `name` is the install and invocation name. */
const FRONTMATTER = `---
name: cog
description: Conventions and code shapes for Swift apps built on Cog, the fine-grained state-management library for SwiftUI. Use when writing or changing Cog state: declarations, reads, CogOps operations, mechanisms, SwiftUI bindings, navigation, tests, or when fixing a coglint finding.
---`;

const GENERATED_NOTICE = (source) =>
  `<!-- Generated by tools/build-cog-skill.mjs from ${source}. Edit that file and run \`mise run skill:build\`. -->`;

main();

function main() {
  const check = process.argv.includes("--check");
  const outputs = render();

  if (check) {
    const stale = outputs.filter(({ path, content }) => readOptional(path) !== content);
    const expected = new Set(outputs.map(({ path }) => path));
    const extra = existingReferences().filter((path) => !expected.has(path));
    if (stale.length > 0 || extra.length > 0) {
      const lines = [
        ...stale.map(({ path }) => `  - ${path} does not match its source`),
        ...extra.map((path) => `  - ${path} has no source`),
      ];
      fail(`the skill is stale; run \`mise run skill:build\`:\n${lines.join("\n")}`);
    }
    console.log(`build-cog-skill: ${outputs.length} generated file(s) match their sources`);
    return;
  }

  rmSync(join(REPO_ROOT, REFERENCES_DIRECTORY), { recursive: true, force: true });
  for (const { path, content } of outputs) {
    mkdirSync(dirname(join(REPO_ROOT, path)), { recursive: true });
    writeFileSync(join(REPO_ROOT, path), content);
  }
  console.log(`build-cog-skill: wrote ${outputs.length} file(s) under ${SKILL_DIRECTORY}/`);
}

/** Every generated file, as `{ path, content }` relative to the repo root. */
function render() {
  const chapters = readdirSync(join(REPO_ROOT, HANDBOOK_DIRECTORY))
    .filter((name) => name.endsWith(".md"))
    .sort();

  const guide = readFileSync(join(REPO_ROOT, GUIDE_PATH), "utf8");
  const skill = [
    FRONTMATTER,
    "",
    GENERATED_NOTICE(GUIDE_PATH),
    "",
    flatten(dropSection(stripFrontmatter(guide), "Point your agent here"), {
      from: GUIDE_PATH,
      linkBase: "references/",
    }),
  ].join("\n");

  const references = chapters.map((name) => {
    const source = `${HANDBOOK_DIRECTORY}/${name}`;
    const content = readFileSync(join(REPO_ROOT, source), "utf8");
    const body = flatten(stripFrontmatter(content), { from: source, linkBase: "./" });
    return {
      path: `${REFERENCES_DIRECTORY}/${referenceName(name)}`,
      content: [GENERATED_NOTICE(source), "", body].join("\n"),
    };
  });

  return [{ path: `${SKILL_DIRECTORY}/SKILL.md`, content: skill }, ...references];
}

/**
 * The handbook index is the one chapter whose filename says nothing on its
 * own once it leaves the `handbook/` directory.
 */
function referenceName(chapter) {
  return chapter === "index.md" ? "handbook.md" : chapter;
}

/** Applies the link and syntax rewrites to one page's Markdown. */
function flatten(markdown, { from, linkBase }) {
  return rewriteLinks(dropFenceLabels(flattenContainers(markdown)), { from, linkBase });
}

function stripFrontmatter(markdown) {
  return markdown.startsWith("---\n")
    ? markdown.replace(/^---\n[\s\S]*?\n---\n\n?/u, "")
    : markdown;
}

/** Removes one `## heading` section, up to the next `## ` heading. */
function dropSection(markdown, heading) {
  const pattern = new RegExp(`^## ${escapeRegExp(heading)}\\n[\\s\\S]*?(?=^## )`, "mu");
  if (!pattern.test(markdown)) fail(`${GUIDE_PATH} no longer has a "${heading}" section`);
  return markdown.replace(pattern, "");
}

/**
 * `::: tip Title` … `:::` becomes a blockquote whose first line is the bold
 * title. Only the container kinds the docs use are handled; an unknown one
 * fails so it cannot ship as literal colons.
 */
function flattenContainers(markdown) {
  return markdown.replace(
    /^::: (tip|warning|info|danger)(?: ([^\n]+))?\n([\s\S]*?)^:::\n/gmu,
    (_match, kind, title, body) => {
      const label = title ?? kind.charAt(0).toUpperCase() + kind.slice(1);
      const lines = body.trimEnd().split("\n");
      return `> **${label}.** ${lines[0]}\n${lines
        .slice(1)
        .map((line) => (line === "" ? ">" : `> ${line}`))
        .join("\n")}\n`;
    },
  );
}

/** ` ```swift [Package.swift]` becomes ` ```swift`. */
function dropFenceLabels(markdown) {
  return markdown.replace(/^(```[a-z]+) \[[^\]]+\]$/gmu, "$1");
}

/**
 * Rewrites relative `.md` links. A link into the handbook points at the
 * copied reference; anything else points at the page's Markdown twin on the
 * published site, which is the same file the docs build emits beside the HTML.
 */
function rewriteLinks(markdown, { from, linkBase }) {
  return markdown.replace(
    /\]\((\.{1,2}\/[^)#\s]+\.md)(#[^)]*)?\)/gu,
    (_match, target, anchor = "") => {
      const resolved = normalize(join(dirname(from), target));
      const handbookPrefix = `${HANDBOOK_DIRECTORY}/`;
      if (resolved.startsWith(handbookPrefix)) {
        const chapter = resolved.slice(handbookPrefix.length);
        if (!chapter.includes("/")) return `](${linkBase}${referenceName(chapter)}${anchor})`;
      }
      if (!resolved.startsWith("docs/")) fail(`${from} links outside docs/: ${target}`);
      const route = resolved.slice("docs/".length).replace(/README\.md$/u, "index.md");
      return `](${SITE_URL}/${route}${anchor})`;
    },
  );
}

function normalize(path) {
  return relative(REPO_ROOT, join(REPO_ROOT, path)).split("\\").join("/");
}

function existingReferences() {
  const directory = join(REPO_ROOT, REFERENCES_DIRECTORY);
  let names;
  try {
    names = readdirSync(directory);
  } catch {
    return [];
  }
  return names.map((name) => `${REFERENCES_DIRECTORY}/${name}`);
}

function readOptional(path) {
  try {
    return readFileSync(join(REPO_ROOT, path), "utf8");
  } catch {
    return null;
  }
}

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

function fail(message) {
  console.error(`build-cog-skill: ${message}`);
  process.exit(1);
}
