#!/usr/bin/env node

// Generates the version-coupled Channel B distribution package from Cog's
// checked-in plugin sources and one already-built artifact checksum.
//
// Usage: `generate-coglint-plugins.mjs [--version 0.4.0] [--output path]
//          [--checksum hex] [--artifact-url https://...zip]`

import {
  copyFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { join, parse, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The Cog repository that owns all distribution inputs. */
const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url));

/** Generated package identity and immutable release asset spelling. */
const PACKAGE_NAME = "CogLintPlugins";
const ASSET_NAME = "CogLintBinary.artifactbundle.zip";

/** A marker that prevents overwriting an unrelated package manifest. */
const GENERATED_MARKER = "Generated by tools/generate-coglint-plugins.mjs";

main(process.argv.slice(2));

/** Parses one release identity and writes every managed distribution file. */
function main(arguments_) {
  const options = parseArguments(arguments_);
  const version = options.version ?? "0.4.0";
  if (!/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(version)) {
    fail(`invalid semantic version: ${version}`);
  }

  const output = resolve(options.output ?? join(REPO_ROOT, ".build", PACKAGE_NAME));
  validateOutput(output);
  const checksum = options.checksum ?? readDefaultChecksum();
  if (!/^[0-9a-f]{64}$/.test(checksum)) {
    fail("checksum must be exactly 64 lowercase hexadecimal characters");
  }

  const artifactURL =
    options.artifactURL ??
    `https://github.com/skeswa/cog/releases/download/${version}/${ASSET_NAME}`;
  validateArtifactURL(artifactURL);

  mkdirSync(output, { recursive: true });
  writeManagedFile(join(output, "Package.swift"), packageManifest(artifactURL, checksum));
  writeManagedFile(join(output, "README.md"), generatedReadme(version));
  writeGenerationRecord(output, version, artifactURL, checksum);
  copyLicense(output);
  copyPlugins(output);

  console.log(`==> Generated ${PACKAGE_NAME} ${version} at ${output}`);
  console.log(`==> Artifact URL: ${artifactURL}`);
  console.log(`==> SwiftPM checksum: ${checksum}`);
}

/** Accepts named options only so release arguments cannot shift position silently. */
function parseArguments(arguments_) {
  const options = {};
  for (let index = 0; index < arguments_.length; index += 1) {
    const option = arguments_[index];
    const value = arguments_[index + 1];
    if (!option.startsWith("--") || value === undefined || value.startsWith("--")) {
      fail(`expected a value after ${option}`);
    }
    switch (option) {
      case "--version":
        options.version = value;
        break;
      case "--output":
        options.output = value;
        break;
      case "--checksum":
        options.checksum = value;
        break;
      case "--artifact-url":
        options.artifactURL = value;
        break;
      default:
        fail(`unknown option: ${option}`);
    }
    index += 1;
  }
  return options;
}

/** Rejects broad or source-owned destinations before touching managed files. */
function validateOutput(output) {
  const forbidden = new Set([
    parse(output).root,
    resolve(homedir()),
    resolve(REPO_ROOT),
    resolve(REPO_ROOT, "swift", "Lint"),
  ]);
  if (forbidden.has(output)) {
    fail(`refusing unsafe output directory: ${output}`);
  }
  if (existsSync(output)) {
    const nonGitEntries = readdirSync(output).filter((entry) => entry !== ".git");
    const recordPath = join(output, ".coglint-generation.json");
    if (nonGitEntries.length > 0 && !existsSync(recordPath)) {
      fail(`refusing nonempty output without a generation record: ${output}`);
    }
    if (existsSync(recordPath)) {
      let record;
      try {
        record = JSON.parse(readFileSync(recordPath, "utf8"));
      } catch {
        fail(`refusing output with an invalid generation record: ${output}`);
      }
      if (record.generator !== "tools/generate-coglint-plugins.mjs") {
        fail(`refusing output owned by another generator: ${output}`);
      }
    }
  }
}

/** Reads the checksum emitted by the artifact build when none is supplied. */
function readDefaultChecksum() {
  const path = join(REPO_ROOT, "swift", "Lint", "Artifacts", `${ASSET_NAME}.checksum`);
  if (!existsSync(path)) {
    fail("no artifact checksum exists; run `mise run build:lint-artifact` first");
  }
  return readFileSync(path, "utf8").trim();
}

/** Requires an HTTPS URL whose last component is the accepted release asset. */
function validateArtifactURL(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    fail(`invalid artifact URL: ${value}`);
  }
  if (url.protocol !== "https:" || url.pathname.split("/").at(-1) !== ASSET_NAME) {
    fail(`artifact URL must be HTTPS and end in ${ASSET_NAME}`);
  }
}

/** Produces the complete dependency-free Channel B package manifest. */
function packageManifest(artifactURL, checksum) {
  return `// swift-tools-version:6.2
// ${GENERATED_MARKER}. Do not edit by hand.

import PackageDescription

let package = Package(
  name: "${PACKAGE_NAME}",
  platforms: [.macOS(.v14)],
  products: [
    .plugin(name: "CogLintBuildToolPlugin", targets: ["CogLintBuildToolPlugin"]),
    .plugin(name: "CogLintCommandPlugin", targets: ["CogLintCommandPlugin"]),
  ],
  targets: [
    .binaryTarget(
      name: "CogLintBinary",
      url: ${JSON.stringify(artifactURL)},
      checksum: ${JSON.stringify(checksum)}
    ),
    .plugin(
      name: "CogLintBuildToolPlugin",
      capability: .buildTool(),
      dependencies: ["CogLintBinary"]
    ),
    .plugin(
      name: "CogLintCommandPlugin",
      capability: .command(
        intent: .custom(
          verb: "coglint",
          description: "Check Swift sources against Cog conventions"
        ),
        permissions: []
      ),
      dependencies: ["CogLintBinary"]
    ),
  ]
)
`;
}

/** Produces the generated repository instructions coupled to one Cog version. */
function generatedReadme(version) {
  return `<!-- ${GENERATED_MARKER}. Do not edit by hand. -->

# CogLint plugins ${version}

This generated package distributes the first-party Cog convention checker for
Cog ${version}. Source, fixtures, documentation, and releases are owned by
[skeswa/cog](https://github.com/skeswa/cog); this repository contains only the
version-coupled binary target and plugin adapters.

Add the package at exactly ${version}, then apply
\`CogLintBuildToolPlugin\` to production targets. Run the same binary on demand
with \`swift package coglint <paths> [--target-role production|test]
[--reporter xcode|github|sarif]\`.
`;
}

/** Writes a machine-readable release record beside the generated manifest. */
function writeGenerationRecord(output, version, artifactURL, checksum) {
  const record = {
    artifactURL,
    checksum,
    generator: "tools/generate-coglint-plugins.mjs",
    package: PACKAGE_NAME,
    version,
  };
  writeFileSync(join(output, ".coglint-generation.json"), `${JSON.stringify(record, null, 2)}\n`);
}

/** Overwrites only files previously owned by this generator. */
function writeManagedFile(path, contents) {
  if (existsSync(path) && !readFileSync(path, "utf8").includes(GENERATED_MARKER)) {
    fail(`refusing to overwrite non-generated file: ${path}`);
  }
  writeFileSync(path, contents);
}

/** Copies the repository license without replacing a different license. */
function copyLicense(output) {
  const source = join(REPO_ROOT, "LICENSE");
  const destination = join(output, "LICENSE");
  if (
    existsSync(destination) &&
    readFileSync(destination, "utf8") !== readFileSync(source, "utf8")
  ) {
    fail(`refusing to overwrite a different license: ${destination}`);
  }
  copyFileSync(source, destination);
}

/** Replaces only the two generator-owned plugin source directories. */
function copyPlugins(output) {
  const pluginRoot = join(output, "Plugins");
  mkdirSync(pluginRoot, { recursive: true });
  for (const name of ["CogLintBuildToolPlugin", "CogLintCommandPlugin"]) {
    const source = join(REPO_ROOT, "swift", "Lint", "Plugins", name);
    const destination = join(pluginRoot, name);
    rmSync(destination, { force: true, recursive: true });
    cpSync(source, destination, { recursive: true });
  }
}

/** Reports a generation failure before a partial package can be published. */
function fail(message) {
  console.error(`error: CogLint distribution generator: ${message}`);
  process.exit(1);
}
